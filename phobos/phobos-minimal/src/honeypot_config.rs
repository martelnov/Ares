use std::fs;
use std::path::Path;

use anyhow::{Context, Result, bail};
use serde::Deserialize;

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct HoneypotConfig {
    pub identity: Identity,
    pub services: Services,
    pub logging: Logging,
    pub security: Security,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Identity {
    pub hostname: String,
    pub fqdn: String,
    pub ip: String,
    pub windows: Windows,
    pub domain: Domain,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Windows {
    pub product: String,
    pub major: u32,
    pub minor: u32,
    pub build: u32,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Domain {
    pub joined: bool,
    pub netbios: String,
    pub dns: String,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Services {
    pub rdp: Rdp,
    pub smb: Smb,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Rdp {
    pub enabled: bool,
    pub bind_address: String,
    pub port: u16,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Smb {
    pub enabled: bool,
    pub port: u16,
    pub generate_config: bool,
    pub output: String,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Logging {
    pub format: String,
    pub path: String,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Security {
    pub allow_interactive_sessions: bool,
    pub always_reject_authentication: bool,
}

impl HoneypotConfig {
    pub fn load(path: &Path) -> Result<Self> {
        let contents = fs::read_to_string(path)
            .with_context(|| format!("cannot read {}", path.display()))?;

        let config: Self = toml::from_str(&contents)
            .with_context(|| format!("invalid TOML in {}", path.display()))?;

        config.validate()?;

        Ok(config)
    }

    fn validate(&self) -> Result<()> {
        if self.security.allow_interactive_sessions {
            bail!("honeypot must not allow interactive sessions");
        }

        if !self.security.always_reject_authentication {
            bail!("honeypot must always reject authentication");
        }

        if !self.services.rdp.enabled {
            bail!("RDP service is disabled");
        }

        if self.services.rdp.port == 0 {
            bail!("invalid RDP port");
        }

        if self.identity.hostname.trim().is_empty()
            || self.identity.fqdn.trim().is_empty()
            || self.identity.domain.netbios.trim().is_empty()
            || self.identity.domain.dns.trim().is_empty()
        {
            bail!("incomplete Windows identity");
        }

        if !self.identity.fqdn.eq_ignore_ascii_case(
            &format!("{}.{}", self.identity.hostname, self.identity.domain.dns)
        ) {
            bail!("FQDN does not match hostname and DNS domain");
        }

        if self.logging.format != "jsonl" {
            bail!("unsupported logging format");
        }

        Ok(())
    }
}

impl HoneypotConfig {
    pub fn ntlm_identity(
        &self,
    ) -> sspi::ntlm::NtlmServerIdentity {
        sspi::ntlm::NtlmServerIdentity {
            netbios_computer_name: self.identity.hostname.clone(),
            netbios_domain_name: self.identity.domain.netbios.clone(),
            dns_computer_name: self.identity.fqdn.clone(),
            dns_domain_name: self.identity.domain.dns.clone(),
        }
    }
}

impl HoneypotConfig {
    /// Generate a standalone Samba configuration matching the RDP identity.
    /// This function never modifies the active Samba configuration.
    pub fn generate_samba_config(&self) -> Result<()> {
        if !self.services.smb.enabled || !self.services.smb.generate_config {
            return Ok(());
        }

        let output = Path::new(&self.services.smb.output);

        let parent = output.parent()
            .context("invalid Samba configuration output path")?;

        fs::create_dir_all(parent)
            .with_context(|| format!("cannot create {}", parent.display()))?;

        let contents = format!(
            "\
# Generated by IronRDP honeypot.
# Recommended standalone Samba configuration.
# This host is NOT joined to Active Directory.
#
# Simulated Windows identity:
# Hostname: {hostname}
# FQDN: {fqdn}
# Windows: {product}
# DNS domain: {dns_domain}
#
# Review with testparm before manual deployment.

[global]
    netbios name = {hostname}
    workgroup = {workgroup}
    server string = {product}
    server role = standalone server

    security = user
    map to guest = Bad User

    server min protocol = SMB2
    server max protocol = SMB3

    load printers = no
    printing = bsd
    printcap name = /dev/null

",
            hostname = self.identity.hostname,
            fqdn = self.identity.fqdn,
            product = self.identity.windows.product,
            dns_domain = self.identity.domain.dns,
            workgroup = self.identity.domain.netbios,
        );

        fs::write(output, contents)
            .with_context(|| format!("cannot write {}", output.display()))?;

        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_samba_config_generation() -> Result<()> {
        let path = Path::new(
            "/AI/apps/rdp-honeypot/config/honeypot.toml"
        );

        let mut config = HoneypotConfig::load(path)?;

        let output = std::env::temp_dir().join(format!(
            "samba-honeypot-test-{}.conf",
            std::process::id()
        ));

        config.services.smb.output =
            output.to_string_lossy().into_owned();

        config.generate_samba_config()?;

        let contents = fs::read_to_string(&output)?;

        assert!(contents.contains("netbios name = FS-DY-01"));
        assert!(contents.contains("workgroup = VYHLEDY"));
        assert!(contents.contains("server role = standalone server"));
        assert!(contents.contains("Windows Server 2019 Standard"));

        fs::remove_file(&output)?;

        Ok(())
    }
}
